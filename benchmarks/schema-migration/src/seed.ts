import { randomUUID } from "node:crypto";

import type { StateJobInfo } from "queuert-schema-v1";
import {
  type StateDump,
  createSeedStateAdapter,
  generateStateDump,
  seedConfig,
} from "queuert-schema-v1/conformance-internal";

export type Seed = {
  scale: number;
  dump: StateDump;
  offsetMs: number;
  orphanedJobIds: Set<string>;
  strandedJobIds: Set<string>;
  blockingChainIds: Set<string>;
  gateChainIds: string[];
};

export type SeedCounts = {
  jobs: number;
  chains: number;
  blockerRows: number;
  continuations: number;
  completedChains: number;
  blocked: number;
  blockedPartly: number;
  running: number;
  orphaned: number;
  stranded: number;
  attemptErrors: number;
};

export const parseScales = (): number[] => {
  const flag = process.argv.find((argument) => argument.startsWith("--scale="));
  return flag === undefined
    ? [1, 10, 100]
    : flag
        .slice("--scale=".length)
        .split(",")
        .map((value) => parseInt(value, 10));
};

const strandedPerScale = 20;
const partlyBlockedPerScale = 200;
const partlyBlockedWorkerId = "00000000-0000-4000-8000-200000000000";

/**
 * Jobs waiting on three chains of which one or two completed, run through the schema v1 in-process
 * adapter: each blocker that completes is claimed, completed and unblocks its dependent.
 */
const generatePartlyBlocked = (scale: number, capturedAt: Date): StateDump => {
  const { stateAdapter, dumpState } = createSeedStateAdapter({
    now: () => capturedAt.getTime(),
    generateJobId: randomUUID,
  });
  const worker = stateAdapter.startWorker({
    workerId: partlyBlockedWorkerId,
    typeNames: ["seed:partly:first"],
    concurrency: 1,
    leaseMs: seedConfig.leaseMs,
  });
  for (let index = 0; index < partlyBlockedPerScale * scale; index++) {
    stateAdapter.withTransaction((txCtx) => {
      const chains = stateAdapter.createJobs({
        txCtx,
        jobs: [
          "seed:partly:first",
          index % 3 === 0 ? "seed:partly:first" : "seed:partly:open",
          "seed:partly:open",
          "seed:partly:dependent",
        ].map((typeName) => ({ id: randomUUID(), typeName, input: { index } })),
      });
      stateAdapter.addJobsBlockers({
        txCtx,
        jobBlockers: [
          { jobId: chains[3].head.id, blockedByChainIds: chains.slice(0, 3).map(({ id }) => id) },
        ],
      });
    });
    for (const job of stateAdapter.startJobAttempts({
      typeNames: ["seed:partly:first"],
      workerId: worker.id,
      workerToken: worker.token,
      limit: 2,
    })) {
      stateAdapter.withTransaction((txCtx) => {
        stateAdapter.completeJobs({
          txCtx,
          jobs: [
            {
              jobId: job.id,
              output: { ok: true },
              attemptToken: job.attemptToken!,
              workerId: job.attemptBy!,
            },
          ],
        });
        stateAdapter.unblockJobs({ txCtx, blockedByChainId: job.chainId });
      });
    }
  }
  return dumpState();
};

/**
 * A dataset generated by the schema v1 seed generator, which runs a simulated week of traffic
 * through the schema v1 state adapter, plus jobs waiting on partly completed blockers and the two
 * leftovers 002 repairs on PostgreSQL and MySQL: the expired seed worker's row is gone, so its
 * running jobs have no worker, and a few pending jobs whose blockers all completed are back in
 * `blocked`, as a lost unblock leaves them.
 */
export const createSeed = (scale: number): Seed => {
  const { dump: simulated } = generateStateDump({ scale });
  const partlyBlocked = generatePartlyBlocked(scale, simulated.capturedAt);
  const generated: StateDump = {
    capturedAt: simulated.capturedAt,
    chains: [...simulated.chains, ...partlyBlocked.chains],
    jobs: [...simulated.jobs, ...partlyBlocked.jobs],
    blockers: [...simulated.blockers, ...partlyBlocked.blockers],
    workers: [...simulated.workers, ...partlyBlocked.workers],
  };
  const workers = generated.workers.filter(({ id }) => id !== seedConfig.expiredWorkerId);
  const workerIds = new Set(workers.map(({ id }) => id));
  const chainStatuses = new Map(generated.chains.map(({ id, status }) => [id, status]));
  const blockerChainIds = new Map<string, string[]>();
  for (const { jobId, blockedByChainId } of generated.blockers) {
    blockerChainIds.set(jobId, [...(blockerChainIds.get(jobId) ?? []), blockedByChainId]);
  }
  const strandedJobIds = new Set(
    generated.jobs
      .filter(
        ({ id, status }) =>
          status === "pending" &&
          (blockerChainIds.get(id) ?? []).length > 0 &&
          blockerChainIds.get(id)!.every((chainId) => chainStatuses.get(chainId) === "completed"),
      )
      .slice(0, strandedPerScale * scale)
      .map(({ id }) => id),
  );
  const jobs: StateJobInfo[] = generated.jobs.map((job) =>
    strandedJobIds.has(job.id) ? { ...job, status: "blocked" } : job,
  );
  return {
    scale,
    dump: { ...generated, jobs, workers },
    offsetMs: Date.now() - generated.capturedAt.getTime(),
    orphanedJobIds: new Set(
      jobs
        .filter(({ status, attemptBy }) => status === "running" && !workerIds.has(attemptBy!))
        .map(({ id }) => id),
    ),
    strandedJobIds,
    blockingChainIds: new Set(generated.blockers.map(({ blockedByChainId }) => blockedByChainId)),
    gateChainIds: generated.chains
      .filter(({ typeName }) => typeName.startsWith("seed:blocker:gate:"))
      .map(({ id }) => id),
  };
};

export const countSeed = ({ dump, orphanedJobIds, strandedJobIds }: Seed): SeedCounts => {
  const chainStatuses = new Map(dump.chains.map(({ id, status }) => [id, status]));
  const blockerChainIds = new Map<string, string[]>();
  for (const { jobId, blockedByChainId } of dump.blockers) {
    blockerChainIds.set(jobId, [...(blockerChainIds.get(jobId) ?? []), blockedByChainId]);
  }
  const blocked = dump.jobs.filter(({ status }) => status === "blocked");
  return {
    jobs: dump.jobs.length,
    chains: dump.chains.length,
    blockerRows: dump.blockers.length,
    continuations: dump.jobs.filter(({ chainIndex }) => chainIndex > 0).length,
    completedChains: dump.chains.filter(({ status }) => status === "completed").length,
    blocked: blocked.length,
    blockedPartly: blocked.filter(({ id }) => {
      const statuses = (blockerChainIds.get(id) ?? []).map((chainId) => chainStatuses.get(chainId));
      return statuses.includes("completed") && statuses.some((status) => status !== "completed");
    }).length,
    running: dump.jobs.filter(({ status }) => status === "running").length,
    orphaned: orphanedJobIds.size,
    stranded: strandedJobIds.size,
    attemptErrors: dump.jobs.filter(({ lastAttemptError }) => lastAttemptError !== null).length,
  };
};
